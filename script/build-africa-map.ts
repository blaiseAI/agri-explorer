/**
 * Generates client/src/components/africa-map/geometry.ts: pre-projected SVG paths for
 * the 54 countries Afrixplorer tracks, so the browser ships no mapping library.
 *
 *   npx tsx script/build-africa-map.ts
 *
 * Source: Natural Earth 1:50m via the world-atlas package. Re-run only if the country
 * list or projection changes.
 */
import { writeFileSync } from "fs";
import { geoAzimuthalEqualArea, geoPath, type GeoPermissibleObjects } from "d3-geo";
import { feature, merge } from "topojson-client";
import { presimplify, simplify, quantile } from "topojson-simplify";
import type { Topology, GeometryCollection } from "topojson-specification";
// eslint-disable-next-line @typescript-eslint/no-var-requires
import world from "world-atlas/countries-50m.json" with { type: "json" };

// ISO 3166-1 numeric -> alpha-3 for the countries in the dataset.
const NUMERIC_TO_ISO3: Record<string, string> = {
  "012": "DZA", "024": "AGO", "204": "BEN", "072": "BWA", "854": "BFA", "108": "BDI",
  "132": "CPV", "120": "CMR", "140": "CAF", "148": "TCD", "174": "COM", "178": "COG",
  "180": "COD", "384": "CIV", "262": "DJI", "818": "EGY", "226": "GNQ", "232": "ERI",
  "748": "SWZ", "231": "ETH", "266": "GAB", "270": "GMB", "288": "GHA", "324": "GIN",
  "624": "GNB", "404": "KEN", "426": "LSO", "430": "LBR", "434": "LBY", "450": "MDG",
  "454": "MWI", "466": "MLI", "478": "MRT", "480": "MUS", "504": "MAR", "508": "MOZ",
  "516": "NAM", "562": "NER", "566": "NGA", "646": "RWA", "678": "STP", "686": "SEN",
  "690": "SYC", "694": "SLE", "706": "SOM", "710": "ZAF", "728": "SSD", "729": "SDN",
  "834": "TZA", "768": "TGO", "788": "TUN", "800": "UGA", "894": "ZMB", "716": "ZWE",
};
// Shown for geographic continuity, never coloured.
const CONTEXT: Record<string, string> = { "732": "Western Sahara" };

const WIDTH = 800;
const HEIGHT = 820;

// Simplify the outlines: full 1:50m detail is ~170 KB, far more than a 800px map needs.
// Drop the 85% least significant points (topojson-simplify keeps points above the quantile).
const SIMPLIFY_QUANTILE = 0.15;
const pre = presimplify(world as unknown as Topology);
const topo = simplify(pre, quantile(pre, SIMPLIFY_QUANTILE)) as unknown as Topology<{ countries: GeometryCollection<{ name: string }> }>;
const geoms = topo.objects.countries.geometries;

// FAOSTAT reports Somalia including Somaliland, so draw them as one shape.
const somalia = merge(topo, geoms.filter((g) => g.id === "706" || g.properties?.name === "Somaliland") as any);

const features = feature(topo, topo.objects.countries).features;
const rawTopo = world as unknown as Topology<{ countries: GeometryCollection<{ name: string }> }>;
const rawFeatures = feature(rawTopo, rawTopo.objects.countries).features;
// Island states are a few pixels wide: keep their full detail (simplification can erase
// them) and give them a marker so they can be seen and tapped.
const ISLAND_STATES = new Set(["CPV", "COM", "MUS", "STP", "SYC"]);
const rawById = new Map(rawFeatures.map((f) => [f.id, f]));

const tracked = features
  .filter((f) => f.id && NUMERIC_TO_ISO3[f.id as string])
  .map((f) => {
    const code = NUMERIC_TO_ISO3[f.id as string];
    const geo = f.id === "706" ? somalia : ISLAND_STATES.has(code) ? rawById.get(f.id)! : f;
    return { code, geo: geo as GeoPermissibleObjects };
  });
const context = features
  .filter((f) => f.id && CONTEXT[f.id as string])
  .map((f) => ({ name: CONTEXT[f.id as string], geo: f as GeoPermissibleObjects }));

if (tracked.length !== 54) throw new Error(`expected 54 countries, got ${tracked.length}`);

const asFeature = (g: any) => (g.type === "Feature" ? g : { type: "Feature", properties: {}, geometry: g });
const projection = geoAzimuthalEqualArea()
  .rotate([-18, -2])
  .fitExtent([[8, 8], [WIDTH - 8, HEIGHT - 8]], { type: "FeatureCollection", features: tracked.map((t) => asFeature(t.geo)) } as any);
const path = geoPath(projection).digits(1);


const countries = tracked
  .map(({ code, geo }) => {
    const [cx, cy] = path.centroid(geo);
    return {
      code,
      d: path(geo) || "",
      cx: Math.round(cx * 10) / 10,
      cy: Math.round(cy * 10) / 10,
      small: ISLAND_STATES.has(code),
    };
  })
  .sort((a, b) => a.code.localeCompare(b.code));

const out = `// Generated by script/build-africa-map.ts — do not edit by hand.
// Natural Earth 1:50m (public domain), azimuthal equal-area projection.
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};
export interface CountryShape { code: string; d: string; cx: number; cy: number; small: boolean }
export const COUNTRY_SHAPES: CountryShape[] = ${JSON.stringify(countries)};
export const CONTEXT_SHAPES: { name: string; d: string }[] = ${JSON.stringify(context.map((c) => ({ name: c.name, d: path(c.geo) || "" })))};
`;
writeFileSync("client/src/components/africa-map/geometry.ts", out);
console.log(`wrote ${countries.length} countries, ${(out.length / 1024).toFixed(0)} KB; small: ${countries.filter((c) => c.small).map((c) => c.code).join(",")}`);
